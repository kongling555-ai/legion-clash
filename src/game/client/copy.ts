export function cardName(
  lang: Lang,
  unit: { defId: string; name: string; fallen: boolean; fallenGod: God | null },
): string {
  if (lang !== "en") {
    if (unit.fallen) return unit.name;
    return unit.name.length > 5 ? unit.name.slice(0, 5) : unit.name;
  }
  if (unit.fallen && unit.fallenGod) return FALLEN_SHORT[unit.fallenGod];
  return SHORT[unit.defId] ?? translateText(lang, unit.name);
}
